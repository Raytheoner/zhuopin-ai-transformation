"""判定用词表 —— 陈忱裁定的**封闭**词表，规则侧与跨模块侧共用的单一可信源。

🔴 **本模块存在的唯一理由：同一个字不能被两条规则各判各的。**

`无` 这个字此前就是这样的：现行规则 12 的同义词集不含它，于是 EQ17（评审委员会判**合格**
的那一份）的 `ASIL=无` 在生产里一直被判「待改进」；而 C06 若另立一套同义词集，同一个字
会被规则 12 与 C06 判出两个相反的结论。陈忱 2026-08-21 回件 Q2 正是**一次把两处定死**，
所以词表也必须只有一份 —— 谁都不许在自己文件里再抄一遍。

判据来源（原文，`7-外部文档/质量部/质量部-ChenChen-回复-2026-08-21-文本反馈-95d6fc3a…md`）：

- **Q2**：「/、NA、N/A、无、不涉及、不适用 均视同 NA；空单元格判「漏填」，不要视同 NA。
  **没有其它常见写法。**」——最后一句是他明确宣告词表**就此封闭**，故本表不留"其它写法"扩展位；
  日后若真出现新写法，走判例批改法回问，不由实现方自行追加。
- **Q3**：「(b)，模块四的「视为没填」词表**直接复用 Q2 那组**，保持口径一致。」
  ⇒ `AS_NOT_FILLED` 不是另一份表，就是同一份，此处只给一个语义化别名，不复制字面量。
"""
from __future__ import annotations

#: 视同「NA／不适用」的 ASIL 写法（陈忱 2026-08-21 Q2，封闭词表）。
#: ⚠️ **空单元格不在其中**——他明确要求空判「漏填」，与「填了一个表示不适用的值」是两回事。
ASIL_NA_SYNONYMS: frozenset[str] = frozenset({
    "/", "NA", "N/A", "无", "不涉及", "不适用",
})

#: 模块四目标格里「字段非空、但语义是没填」的写法（陈忱 2026-08-21 Q3 选 (b)：复用 Q2 那组）。
#: 别名而非副本——两者若哪天需要分开，必须由他再裁一次，不能靠这里悄悄分叉。
AS_NOT_FILLED_SYNONYMS: frozenset[str] = ASIL_NA_SYNONYMS


def is_na_synonym(value) -> bool:
    """判一个已填值是否属「视同 NA」的写法。

    **空值一律返回 False**——空的语义是「漏填」，由调用方各自处置（规则 12 判不合格、
    C06 判转人工），本函数不替它们把空悄悄归成 NA。这正是 Q2 那半句要防的事。

    大小写不敏感只对 `NA`／`N/A` 这类拉丁写法有意义，中文写法不受影响。
    """
    if value is None:
        return False
    v = str(value).strip()
    if not v:
        return False
    return v.upper() in {s.upper() for s in ASIL_NA_SYNONYMS}


def is_as_not_filled(value) -> bool:
    """判模块四目标格是否「视为没填」——真空 或 填了 Q2 那组同义词之一。

    与 `is_na_synonym` 的差别只在**空值**：那边空是「漏填」要单独报，这里空本来就是没填。
    """
    if value is None:
        return True
    v = str(value).strip()
    return (not v) or is_na_synonym(v)
